//! Migration 050: Add `keyring_secret_fields` column to `cfg_connection_profiles`.
//!
//! Stores, as a JSON array, the ids of the secret form fields (other than the
//! primary password) whose value the OS keyring holds for the connection. The
//! values themselves are never stored here. Existing profiles have none.

use rusqlite::Transaction;

use crate::migrations::{Migration, MigrationError};

pub(crate) struct MigrationImpl;

impl Migration for MigrationImpl {
    fn name(&self) -> &str {
        "050_connection_profile_keyring_secret_fields"
    }

    fn run(&self, tx: &Transaction) -> Result<(), MigrationError> {
        let table_exists: bool = tx
            .query_row(
                "SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND name='cfg_connection_profiles'",
                [],
                |row| row.get::<_, i64>(0),
            )
            .map(|count| count > 0)
            .map_err(sqlite_err)?;

        if !table_exists {
            return Ok(());
        }

        let column_exists: bool = tx
            .query_row(
                "SELECT COUNT(*) FROM pragma_table_info('cfg_connection_profiles') WHERE name = 'keyring_secret_fields'",
                [],
                |row| row.get::<_, i64>(0),
            )
            .map(|count| count > 0)
            .map_err(sqlite_err)?;

        if !column_exists {
            tx.execute_batch(
                "ALTER TABLE cfg_connection_profiles ADD COLUMN keyring_secret_fields TEXT;",
            )
            .map_err(sqlite_err)?;
        }

        Ok(())
    }
}

fn sqlite_err(source: rusqlite::Error) -> MigrationError {
    MigrationError::Sqlite {
        path: std::path::PathBuf::from("<050_connection_profile_keyring_secret_fields>"),
        source,
    }
}
